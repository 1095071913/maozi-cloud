package com.maozi.common.constant;

/**
 * 通用符号常量类
 * <p>
 * 集中定义项目内常用的符号字符串常量，避免业务代码中出现魔法值。
 * </p>
 *
 * @author maozi
 * @date 2026/11/19
 */
public final class SymbolConstant {

    /** 空字符串 */
    public static final String EMPTY = "";

    /** 英文句点 */
    public static final String DOT = ".";

    /** 中文句号 */
    public static final String CHINESE_PERIOD = "。";

    /** 反斜杠 */
    public static final String BACKSLASH = "\\";

    /** 正斜杠 */
    public static final String SLASH = "/";

    /** 逗号 */
    public static final String COMMA = ",";

    /** 冒号 */
    public static final String COLON = ":";

    /** 下划线 */
    public static final String UNDERLINE = "_";

    /** 连字符 */
    public static final String HYPHEN = "-";

    /** 空格 */
    public static final String SPACE = " ";

    /** 分号 */
    public static final String SEMICOLON = ";";

    /** 问号 */
    public static final String QUESTION_MARK = "?";

    /** 星号 */
    public static final String ASTERISK = "*";

    /** 单引号 */
    public static final String SINGLE_QUOTE = "'";

    /** 左圆括号 */
    public static final String LEFT_PARENTHESIS = "(";

    /** 右圆括号 */
    public static final String RIGHT_PARENTHESIS = ")";

    /** 正斜杠字符（供 indexOf、append 等 char 参数场景使用） */
    public static final char SLASH_CHAR = '/';

    /** 冒号字符（供 indexOf、append 等 char 参数场景使用） */
    public static final char COLON_CHAR = ':';

    /** 问号字符（供 indexOf、append 等 char 参数场景使用） */
    public static final char QUESTION_MARK_CHAR = '?';

}
